"""Turn the drawing questions of already-ingested papers into "pick the drawing" (2026-10-12), as ingest.py --from-json now does,
without cropping the figures again: out/<id>/paper.json gets the MCQs, paper.js is rebuilt from it and report.json's figures.
Run once per paper: python tools/ingest/apply_pictures.py <id> [<id> ...] (it refuses a paper already converted)."""
import json
import sys
from pathlib import Path

import pictures
import validate

HERE = Path(__file__).parent

for pid in sys.argv[1:]:
    out = HERE / "out" / pid
    paper = json.loads((out / "paper.json").read_text(encoding="utf-8"))
    report = json.loads((out / "report.json").read_text(encoding="utf-8"))
    done = pictures.apply(pid, paper)
    issues = validate.check(paper)
    # a schema error is named by its path ("sections/0/missions/1/items/3"), not a part number: every one counts (2026-10-12: the
    # schema had no `pics`, and its errors on the new MCQs were filtered out here)
    bad = [x for x in issues if x["n"] in done or "/" in x["n"]]
    for x in bad:
        print(f"  {x['severity']:5} {x['n']:10} {x['msg']}")
    if any(x["severity"] == "error" for x in bad):
        sys.exit(f"{pid}: the new MCQs have errors (nothing written)")
    app = validate.to_app(paper, pid, report.get("figures", {}))
    (out / "paper.json").write_text(json.dumps(paper, indent=1, ensure_ascii=False), encoding="utf-8")
    (out / "paper.js").write_text("// generated by tools/ingest/ingest.py: do not edit; re-run the ingest instead\n"
                                  "window.PAPERS_INGESTED = (window.PAPERS_INGESTED || []).concat([" + json.dumps(app, ensure_ascii=False) + "]);\n",
                                  encoding="utf-8")
    print(f"{pid}: {len(done)} drawing parts now pick the drawing: {', '.join(done)}")
